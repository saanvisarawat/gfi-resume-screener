// Builds data/candidates.json from the raw resumes.
// Usage:  npm run data            (reads data/raw)
//         npm run data -- <dir>   (reads another folder)
import fs from "fs";
import path from "path";
import mammoth from "mammoth";
import { fileToText } from "../lib/parse";
import { extractCandidate } from "../lib/extract";
import { scoreCandidate } from "../lib/score";
import type { Scored } from "../lib/types";

export const AS_OF = "2026-11-09"; // 'Present' in resumes is read as this date, so results never drift

export async function main() {
  const src = process.argv[2] ?? path.join("data", "raw");
  const files = fs.readdirSync(src).filter(f => /\.(docx|pdf|txt)$/i.test(f)).sort();
  if (!files.length) throw new Error(`No resumes found in ${src}`);
  fs.mkdirSync("public/resumes", { recursive: true });
  fs.rmSync("data/text", { recursive: true, force: true });
  fs.mkdirSync("data/text", { recursive: true });
  const out: Scored[] = [];
  const seen = new Set<string>();
  const tables: Record<string, number> = {};
  for (const f of files) {
    const m = f.match(/^(?:anonymized_)?(.+?)_(\d+)\.\w+$/);
    let id = m ? `${m[1]}-${m[2].slice(-4)}` : f.replace(/\.\w+$/, "");
    if (/^resume/i.test(id)) id = `resume-${id.split("-").pop()}`;
    if (seen.has(id)) id = `${id}-${seen.size}`;
    seen.add(id);
    const buf = fs.readFileSync(path.join(src, f));
    let text = "", readError = "";
    try { text = await fileToText(buf, f); } catch (e) { readError = (e as Error).message; }
    if (/\.docx$/i.test(f)) { try { tables[id] = ((await mammoth.convertToHtml({ buffer: buf })).value.match(/<table/g) ?? []).length; } catch { tables[id] = -1; } }
    fs.writeFileSync(path.join("data/text", `${id}.txt`), text);
    fs.copyFileSync(path.join(src, f), path.join("public/resumes", f));
    const c = extractCandidate(text, { id, sourceFile: f, sourceUrl: `/resumes/${encodeURIComponent(f)}` }, new Date(AS_OF));
    if (readError) c.warnings.unshift({ level: "error", code: "READ_ERROR", message: `The file could not be opened: ${readError}` });
    out.push(scoreCandidate(c));
  }
  fs.writeFileSync("data/candidates.json", JSON.stringify({ builtAt: AS_OF, candidates: out }));
  // ---- docs/CLEANING.md: what was actually cleaned or flagged, per resume (generated, never hand-written)
  const lines = ["# Data cleaning log", "", `Generated by \`npm run data\` from ${out.length} resumes (as-of date ${AS_OF}).`, "",
    "Cleaning is rule-based and deterministic. Each action below was applied to the extracted text, or each problem was flagged for a human, by code in `lib/extract.ts`.", ""];
  const codes: Record<string, number> = {};
  for (const c of out) for (const w of c.warnings) codes[w.code] = (codes[w.code] ?? 0) + 1;
  lines.push("## Summary of warnings", "", "| Code | Resumes |", "|---|---|", ...Object.entries(codes).sort().map(([k, v]) => `| ${k} | ${v} |`), "");
  lines.push("## Per resume", "", "| Resume | Status | Text clean-up applied | Warnings |", "|---|---|---|---|");
  for (const c of out) {
    const acts = [...new Set(c.cleaning)].join("; ") || "none needed";
    const ws = c.warnings.map(w => `${w.level}: ${w.code}`).join(", ") || "none";
    lines.push(`| ${c.id} | ${c.status} | ${acts} | ${ws} |`);
  }
  fs.mkdirSync("docs", { recursive: true });
  fs.writeFileSync("docs/CLEANING.md", lines.join("\n") + "\n");
  // ---- docs/DATA_AUDIT.md: what the corpus looks like (generated, so it can never drift from the data)
  const audit = ["# Data audit", "", `Generated by \`npm run data\`. ${out.length} files.`, ""];
  const ext: Record<string, number> = {}; for (const c of out) { const e = c.sourceFile.split(".").pop()!; ext[e] = (ext[e] ?? 0) + 1; }
  audit.push(`- File types: ${Object.entries(ext).map(([k, v]) => `${v} .${k}`).join(", ")}`);
  audit.push(`- Resumes containing Word tables (a sign of multi-column layouts): ${Object.values(tables).filter(v => v > 0).length}`);
  audit.push(`- Readable: ${out.filter(c => c.status !== "unreadable").length}; unreadable: ${out.filter(c => c.status === "unreadable").map(c => c.id).join(", ") || "none"}`);
  const ini: Record<string, string[]> = {}; for (const c of out) (ini[c.id.split("-")[0]] ??= []).push(c.id);
  audit.push(`- Initials shared by more than one resume (so initials cannot be used as an ID): ${Object.entries(ini).filter(([, v]) => v.length > 1).map(([k, v]) => `${k} x${v.length}`).join(", ") || "none"}`);
  audit.push("- Text boxes and images inside Word files are not read by the parser; they were not checked separately.", "");
  audit.push("| Resume | File | Characters | Headline | Roles | Education | Projects | Experience (months) | Tables | Status |", "|---|---|---|---|---|---|---|---|---|---|");
  for (const c of out) audit.push(`| ${c.id} | ${c.sourceFile} | ${c.textLength} | ${c.headline.replace(/\|/g, "/")} | ${c.jobs.length} | ${c.education.length} | ${c.projects.length} | ${c.totalMonths} | ${tables[c.id] ?? "-"} | ${c.status} |`);
  fs.writeFileSync("docs/DATA_AUDIT.md", audit.join("\n") + "\n");
  const by = (s: string) => out.filter(c => c.status === s).length;
  console.log(`Built ${out.length} candidates (ok ${by("ok")}, partial ${by("partial")}, unreadable ${by("unreadable")}) -> data/candidates.json`);
}
if (process.argv[1]?.endsWith("build-data.ts")) main();
